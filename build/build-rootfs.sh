#!/bin/bash
# build-rootfs.sh — build the Qua Station Ubuntu 26.04 root filesystem tarball.
# Host: any x86_64/arm64 Linux with qemu-user-binfmt (for arm64 chroot on x86), tar, sudo.
# Usage: sudo ./build-rootfs.sh <ubuntu-base-26.04.x-base-arm64.tar.gz> <modules-dir(lib/modules/<rel>)> <outdir>
set -euo pipefail
[ -n "${DEBUG:-}" ] && set -x
BASE=${1:?ubuntu-base tarball}; MODS=${2:?path to lib/modules/<release>}; OUT=${3:?output dir}
HERE=$(cd "$(dirname "$0")/.." && pwd); OVL=$HERE/overlay
DIST_USER=${DIST_USER:-qua}; DIST_PASS=${DIST_PASS:-qua}
W=$(mktemp -d /var/tmp/qua-rootfs.XXXX); R=$W/rootfs; mkdir -p "$R" "$OUT"
echo "[1/7] extracting $BASE"; tar -xzf "$BASE" -C "$R"
cp /etc/resolv.conf "$R/etc/resolv.conf"
mount -t proc proc "$R/proc"; mount --bind /sys "$R/sys"; mount --bind /dev "$R/dev"; mount --bind /dev/pts "$R/dev/pts"
trap 'umount -l "$R/dev/pts" "$R/dev" "$R/sys" "$R/proc" 2>/dev/null; [ -n "${KEEP:-}" ] && echo "kept $W" || rm -rf "$W"' EXIT
ch(){ chroot "$R" /usr/bin/env DEBIAN_FRONTEND=noninteractive LANG=C.UTF-8 "$@"; }
PKGS="systemd systemd-sysv systemd-resolved systemd-timesyncd systemd-zram-generator udev kmod dbus
 openssh-server sudo passwd login iproute2 iputils-ping net-tools ethtool wpasupplicant iw rfkill
 bluez gpiod i2c-tools pciutils usbutils python3 e2fsprogs parted cloud-guest-utils smartmontools
 fake-hwclock tzdata ca-certificates curl wget rsync less vim-tiny nano htop tmux tcpdump lsof strace bash-completion"
echo "[2/7] apt"; ch apt-get -qq update
ch apt-get -qq -y --no-install-recommends install $PKGS >/dev/null
echo "[3/7] overlay"; cp -a "$OVL"/. "$R"/
echo "[4/7] kernel modules $(basename "$MODS")"; mkdir -p "$R/usr/lib/modules"; cp -a "$MODS" "$R/usr/lib/modules/"
ch depmod -a "$(basename "$MODS")"
echo "[5/7] users & services"
ch groupadd -f plugdev; ch useradd -m -s /bin/bash -G sudo,adm,dialout,plugdev "$DIST_USER"
echo "$DIST_USER:$DIST_PASS" | ch chpasswd
ch chage -d 0 "$DIST_USER"            # force password change at first login
ch passwd -l root >/dev/null 2>&1 || true   # root has no password in ubuntu-base already
ch systemctl enable systemd-networkd systemd-resolved systemd-timesyncd ssh \
   qua-firstboot qua-uart1-pinmux rtk-bluetooth bluetooth qua-boot-led qua-iowd
ch systemctl disable systemd-networkd-wait-online >/dev/null 2>&1 || true
ln -sf /usr/share/zoneinfo/UTC "$R/etc/localtime"; echo UTC > "$R/etc/timezone"
echo "[6/7] cleanup"
ch apt-get -qq clean; rm -rf "$R"/var/lib/apt/lists/* "$R"/var/cache/apt/*.bin "$R"/var/log/*.log "$R"/var/log/journal/*
rm -f "$R"/etc/ssh/ssh_host_*            # regenerated by qua-firstboot on first boot
: > "$R/etc/machine-id"; rm -f "$R/var/lib/dbus/machine-id"
rm -f "$R/etc/resolv.conf"; ln -s ../run/systemd/resolve/stub-resolv.conf "$R/etc/resolv.conf"
rm -rf "$R"/root/.bash_history "$R"/tmp/* "$R"/var/tmp/*
umount "$R/dev/pts" "$R/dev" "$R/sys" "$R/proc"; trap 'rm -rf "$W"' EXIT
for l in lib bin sbin; do [ -L "$R/$l" ] || { echo "ERROR: /$l is not a symlink (usrmerge broken)"; exit 1; }; done
echo "[7/7] packing"; T=$OUT/quastation-ubuntu2604-rootfs.tar.gz
tar --numeric-owner --xattrs -czf "$T" -C "$R" .
( cd "$OUT" && sha256sum "$(basename "$T")" > "$(basename "$T").sha256" )
du -sh "$R" | cut -f1; ls -la "$T"; echo "user=$DIST_USER pass=$DIST_PASS (change forced at first login)"
